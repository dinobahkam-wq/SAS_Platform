import { MediaUploadForm } from "@/components/media-upload-form";
import { requireAdmin } from "@/lib/admin";

export default async function MediaPage({
  searchParams,
}: {
  searchParams: Promise<{ uploaded?: string; error?: string }>;
}) {
  const params = await searchParams;
  const { supabase } = await requireAdmin();
  const { data: assets, error } = await supabase
    .from("media_assets")
    .select("*")
    .order("created_at", { ascending: false })
    .limit(60);

  const errorMessages: Record<string, string> = {
    file: "الملف غير صالح أو يتجاوز الحجم المسموح.",
    upload: "فشل رفع الملف إلى Storage. تحقق من إعدادات الحاوية والصلاحيات.",
    metadata: "رُفع الملف لكن تعذر تسجيل بياناته. تمت محاولة حذف الملف غير المرتبط.",
  };

  return (
    <>
      <div className="page-heading">
        <div><span className="eyebrow">الأصول الرقمية</span><h1>مكتبة الوسائط</h1><p>إدارة الصور المستخدمة في الأخبار والتحليلات والدراسات.</p></div>
      </div>
      {params.uploaded ? <div className="notice notice-success">تم رفع الصورة وتسجيل بياناتها.</div> : null}
      {params.error && errorMessages[params.error] ? <div className="notice notice-error">{errorMessages[params.error]}</div> : null}

      <div className="admin-grid">
        <section className="panel">
          <div className="panel-header"><h2>الصور المضافة</h2><span className="pill">{assets?.length ?? 0} صورة</span></div>
          {error ? <div className="empty-state">تعذر تحميل مكتبة الوسائط.</div> : assets?.length ? (
            <div className="panel-body"><div className="media-grid">
              {assets.map((asset) => {
                const { data } = supabase.storage.from(asset.bucket_id).getPublicUrl(asset.object_path);
                return <article className="media-card" key={asset.id}>
                  {/* Public bucket; URL is generated by Supabase Storage. */}
                  <img src={data.publicUrl} alt={asset.alt_text ?? asset.file_name} />
                  <div><strong>{asset.file_name}</strong><p className="helper-text">{asset.width ?? "?"} × {asset.height ?? "?"} · {(asset.file_size / 1024).toFixed(0)} KB</p><a href={data.publicUrl} target="_blank" rel="noreferrer" className="table-title">فتح الصورة ↗</a></div>
                </article>;
              })}
            </div></div>
          ) : <div className="empty-state">مكتبة الوسائط فارغة. ارفع أول صورة للمنصة.</div>}
        </section>

        <section className="panel">
          <div className="panel-header"><h2>رفع صورة جديدة</h2></div>
          <div className="panel-body"><MediaUploadForm /></div>
        </section>
      </div>
    </>
  );
}
